const translationKeys = new Map(Object.entries(DICTIONARY.en).map(([key, value]) => [value, key]));

export function initialLanguage(): Lang {
  try {
    const saved =
      typeof localStorage === 'undefined' ? null : localStorage.getItem('ai_vision_lang');
    if (saved === 'ar' || saved === 'en') return saved;
  } catch {
    // Browsers may disable storage; translation still works for this visit.
  }
  return 'ar';
}

export function translate(
  lang: Lang,
  key: string | null | undefined,
  params: Record<string, string | number> = {},
): string {
  if (key == null) return '';
  const trimmed = key.trim().replace(/\s+/g, ' ');
  const resolved = translationKeys.get(trimmed) ?? trimmed;
  const translated = DICTIONARY[lang][resolved] ?? DICTIONARY.en[resolved];
  const text =
    translated == null
      ? key
      : `${key.match(/^\s*/)?.[0] ?? ''}${translated}${key.match(/\s*$/)?.[0] ?? ''}`;
  return text.replace(/\{(\w+)\}/g, (match, name: string) => String(params[name] ?? match));
}

@Injectable({ providedIn: 'root' })
export class I18nService {
  readonly currentLang = signal<Lang>(initialLanguage());
  readonly dir = computed<Dir>(() => (this.currentLang() === 'ar' ? 'rtl' : 'ltr'));

  constructor() {
    this.applyDocumentDir(this.currentLang(), this.dir());
  }

  setLang(lang: Lang): void {
    this.currentLang.set(lang);
    try {
      if (typeof localStorage !== 'undefined') localStorage.setItem('ai_vision_lang', lang);
    } catch {
      // Keep the selected language even when preferences cannot be persisted.
    }
    this.applyDocumentDir(lang, this.dir());
  }

  toggleLang(): void {
    this.setLang(this.currentLang() === 'ar' ? 'en' : 'ar');
  }

  errorMessage(error: UiError): string {
    if (this.currentLang() === 'en') return error.message;
    const translated = this.t(error.message);
    if (translated !== error.message || /[\u0600-\u06ff]/.test(error.message)) return translated;
    return this.t(
      API_ERROR_MESSAGES[error.status ?? 500] ??
        'Something went wrong on the server. Please retry.',
    );
  }

  private applyDocumentDir(lang: Lang, dir: Dir): void {
    if (typeof document !== 'undefined' && document.documentElement) {
      document.documentElement.setAttribute('lang', lang);
      document.documentElement.setAttribute('dir', dir);
    }
  }

  t(key: string | null | undefined, params: Record<string, string | number> = {}): string {
    return translate(this.currentLang(), key, params);
  }
}

@Pipe({
  name: 't',
  standalone: true,
  pure: false,
})
export class TranslatePipe implements PipeTransform {
  private readonly i18n = inject(I18nService);

  transform(key: string | null | undefined, params?: Record<string, string | number>): string {
    return this.i18n.t(key, params);
  }
}
